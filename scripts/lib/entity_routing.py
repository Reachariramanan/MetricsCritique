"""Prompts, validators and helpers for Gemma domain routing and L1/L2 entity extraction.

Pure functions only (no network, no DB) so they are unit-testable without the endpoint.
The entity vocabulary comes from `data/entity_schema.json`, generated by
`scripts/build_entity_schema.py` from `docs/entities/ENTITIES_EXTRACTED_Final.md`:

  L1 = core types asked on every post (locations, initiator, target, mode, outcome, date)
  L2 = the domain-specific types of the domain a post is routed to (D01-D09)
"""
from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache
from typing import Optional

from .config import ENTITY_SCHEMA_PATH

EVENT_MODES = ("factual", "future", "hypothetical", "negated", "claimed", "none")
NONE_DOMAIN = "none"
MAX_TEXT_CHARS = 1500
MIN_TEXT_CHARS = 40


@lru_cache(maxsize=1)
def load_schema() -> dict:
    return json.loads(ENTITY_SCHEMA_PATH.read_text(encoding="utf-8"))


def domain_ids() -> list[str]:
    return list(load_schema()["domain_ids"])


def domain_bucket(domain: Optional[str]) -> Optional[str]:
    if not domain or domain == NONE_DOMAIN:
        return None
    return load_schema()["l2"][domain]["bucket"]


# ----------------------------------------------------------------------------
# Routing
# ----------------------------------------------------------------------------
def routing_system_prompt() -> str:
    s = load_schema()
    lines = [f"- {d}: {s['l2'][d]['name']} (bucket: {s['l2'][d]['bucket']})"
             for d in domain_ids()]
    return (
        "You classify short social-media posts (any language) into ONE security/geopolitical "
        "domain. Domains:\n" + "\n".join(lines) + f"\n- {NONE_DOMAIN}: not about any of the above "
        "(entertainment, sport, personal chatter, ads, spam).\n\n"
        "Reply with ONE JSON object and nothing else:\n"
        '{"domain_1": "<D01..D09|none>", "confidence_1": <0..1>, '
        '"domain_2": "<D01..D09|none>", '
        f'"event_mode": "<{"|".join(EVENT_MODES)}>", '
        '"evidence": "<verbatim quote of at most 25 words from the post, in its original language>"}\n'
        "domain_2 is the runner-up domain if the post plausibly fits two, else \"none\". "
        "event_mode: factual = reported as having happened; future = planned/scheduled/threatened; "
        "hypothetical = speculation; negated = reports that something did NOT happen; "
        "claimed = a party's claim or denial; none = no event. "
        "Use only the enumerated values. Do not translate the evidence."
    )


def routing_user_prompt(text: str) -> str:
    return "Post:\n" + text[:MAX_TEXT_CHARS]


def validate_route(obj: dict) -> Optional[str]:
    valid = set(domain_ids()) | {NONE_DOMAIN}
    d1, d2 = obj.get("domain_1"), obj.get("domain_2", NONE_DOMAIN)
    if d1 not in valid:
        return f"domain_1={d1!r}"
    if d2 not in valid:
        return f"domain_2={d2!r}"
    if d2 == d1 and d1 != NONE_DOMAIN:
        return "domain_2 equals domain_1"
    if obj.get("event_mode", "none") not in EVENT_MODES:
        return f"event_mode={obj.get('event_mode')!r}"
    try:
        c = float(obj.get("confidence_1"))
    except (TypeError, ValueError):
        return "confidence_1 not a number"
    if not 0.0 <= c <= 1.0:
        return "confidence_1 out of range"
    return None


# ----------------------------------------------------------------------------
# Entity extraction
# ----------------------------------------------------------------------------
def allowed_types(domains: list[str]) -> dict[str, dict]:
    """type -> {level, domain, capture} for L1 plus the L2 types of the given domains."""
    s = load_schema()
    out: dict[str, dict] = {}
    for t in s["l1"]:
        out[t["type"]] = {"level": "L1", "domain": None, "capture": t["capture"]}
    for d in domains:
        if d == NONE_DOMAIN or d not in s["l2"]:
            continue
        for t in s["l2"][d]["types"]:
            out.setdefault(t["type"], {"level": "L2", "domain": d, "capture": t["capture"]})
    return out


def entity_system_prompt(domains: list[str]) -> str:
    types = allowed_types(domains)
    # The list line is `- TYPE: what to capture`. It must NOT carry a `[L1]`/`[L2]` suffix next to the
    # type: Gemma copied it into the answer (`"type": "LOC_COUNTRY [L1]"`), which the validator rejected
    # (about 21-64% of extractions failed). The level is assigned by code from allowed_types(), not by Gemma.
    lines = [f"- {t}: {m['capture']}" for t, m in types.items()]
    return (
        "Extract named entities from a social-media post (any language). Only use these "
        "entity types:\n" + "\n".join(lines) + "\n\n"
        "`type` must be exactly one identifier from the start of a line above (for example LOC_COUNTRY), "
        "with no brackets, level tags or other text.\n\n"
        "Reply with ONE JSON object and nothing else:\n"
        '{"entities": [{"type": "<TYPE>", "name": "<surface form exactly as written>", '
        '"canonical": "<normalised English name>", "role": "<short role, e.g. initiator, '
        'target, event_place, origin, or empty>", "confidence": <0..1>, '
        '"evidence": "<verbatim quote of at most 25 words containing the name>"}]}\n'
        "Rules: extract only entities the post actually states; never infer or invent. "
        "Return {\"entities\": []} if there are none. Do not use a type that is not listed. "
        "Keep `name` and `evidence` in the post's original language and script."
    )


def entity_user_prompt(text: str) -> str:
    return "Post:\n" + text[:MAX_TEXT_CHARS]


_TYPE_SUFFIX = re.compile(r"\s*[\[(][^\])]*[\])]\s*$")


def clean_type(t):
    """`'LOC_COUNTRY [L1]'` -> `'LOC_COUNTRY'`. Only a trailing [...] or (...) tag is removed; anything else is
    returned unchanged so a genuinely wrong type is still rejected by the validator."""
    return _TYPE_SUFFIX.sub("", t).strip() if isinstance(t, str) else t


def validate_entities(obj: dict, domains: list[str]) -> Optional[str]:
    """Returns None if acceptable, else a reason. Side effect: strips a stray `[L1]`-style tag from each
    entity's `type` IN PLACE, so the object that gets stored carries the clean type name."""
    ents = obj.get("entities")
    if not isinstance(ents, list):
        return "entities is not a list"
    allowed = allowed_types(domains)
    for e in ents:
        if not isinstance(e, dict):
            return "entity is not an object"
        e["type"] = clean_type(e.get("type"))
        if e.get("type") not in allowed:
            return f"type={e.get('type')!r} not allowed"
        if not str(e.get("name") or "").strip():
            return "empty name"
        try:
            if not 0.0 <= float(e.get("confidence", 0.0)) <= 1.0:
                return "confidence out of range"
        except (TypeError, ValueError):
            return "confidence not a number"
    return None


# ----------------------------------------------------------------------------
# Shared helpers
# ----------------------------------------------------------------------------
def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", s)).strip().casefold()


def evidence_in_text(evidence: str, text: str) -> bool:
    """Verbatim check (whitespace/case/Unicode-normalised). Empty evidence is not evidence."""
    ev = _norm(evidence or "")
    return bool(ev) and ev in _norm(text)


def name_key(name: str) -> str:
    """Stable merge key for an entity surface form (NFKC, casefold, collapsed whitespace,
    CJK inter-character spaces removed as in script 10)."""
    k = _norm(name)
    return re.sub(r"(?<=[一-鿿㐀-䶿])\s+(?=[一-鿿㐀-䶿])", "", k)


# ----------------------------------------------------------------------------
# Post selection (read-only; imported lazily so the module stays import-light)
# ----------------------------------------------------------------------------
def select_posts(limit: Optional[int], seed: int, since: Optional[str],
                 skip_uids: set[str], newest_first: bool = False) -> "list[tuple[str, str, str, str]]":
    """(post_uid, platform, lang, text) for posts long enough to classify.

    Deterministic order by hash(post_uid, seed), so a pilot is a reproducible random
    sample and a resumed run continues the same sequence. `skip_uids` are already done.
    """
    import duckdb

    from .config import DUCKDB_PATH

    con = duckdb.connect(str(DUCKDB_PATH), read_only=True)
    try:
        where = [f"length(trim(text)) >= {MIN_TEXT_CHARS}"]
        if since:
            where.append(f"coalesce(posted_at, scraped_at) >= TIMESTAMPTZ '{since}'")
        rows = con.execute(
            "SELECT post_uid, platform, coalesce(lang,'und'), text FROM post_facts "
            f"WHERE {' AND '.join(where)} ORDER BY "
            + ("coalesce(posted_at, scraped_at) DESC, post_uid" if newest_first
               else f"hash(post_uid || '{int(seed)}')")
        ).fetchall()
    finally:
        con.close()
    out = [r for r in rows if r[0] not in skip_uids]
    # Newly seen posts always go first (priority), then the backlog newest-first.
    queued = load_incoming(skip_uids)
    seen = {r[0] for r in queued}
    out = queued + [r for r in out if r[0] not in seen]
    return out[:limit] if limit else out


# ----------------------------------------------------------------------------
# Priority queue: posts seen by scripts/watch_new_posts.py (newest first) jump the backlog
# ----------------------------------------------------------------------------
def _incoming_con():
    import time

    import duckdb

    from .config import DATA_DIR
    path = DATA_DIR / "incoming_posts.duckdb"
    if not path.exists():
        return None
    for _ in range(10):
        try:
            return duckdb.connect(str(path), read_only=True)
        except duckdb.IOException:
            time.sleep(0.5)          # the watcher has it open for a moment
    return None


def load_incoming(skip_uids: set[str]) -> "list[tuple[str, str, str, str]]":
    """Queued new posts as (post_uid, platform, lang, text), newest scraped first."""
    con = _incoming_con()
    if con is None:
        return []
    try:
        rows = con.execute(
            "SELECT post_uid, platform, coalesce(lang,'und'), text FROM incoming_posts "
            f"WHERE length(trim(text)) >= {MIN_TEXT_CHARS} "
            "ORDER BY coalesce(scraped_at, posted_at) DESC, post_uid").fetchall()
    finally:
        con.close()
    return [r for r in rows if r[0] not in skip_uids]


def incoming_texts(uids: list[str]) -> dict[str, str]:
    con = _incoming_con()
    if con is None or not uids:
        return {}
    try:
        return dict(con.execute(
            "SELECT post_uid, text FROM incoming_posts WHERE post_uid IN (SELECT unnest(?))",
            [uids]).fetchall())
    finally:
        con.close()
